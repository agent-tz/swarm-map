import { describe, it, expect } from 'vitest'
import { generateStandaloneCompose, bindUnpinnedPorts, DEFAULT_API_BIND_HOST } from '@/lib/services/harness-compose'
import { generateAgentCompose } from '@/lib/services/agent-deploy-templates'
import { parsePublishedPorts } from '@/lib/services/harness'
import { validateSettingsPatch } from '@/lib/services/config'

type Port = { host_ip?: string; published: number; target: number }
// Minimal reader for the long-syntax port entries HSM emits: slice the named
// service's block, then read each `- host_ip/published/target` entry. Fails the
// test (empty array) if the shape drifts, rather than passing vacuously.
function portsOf(compose: string, service: string): Port[] {
  const lines = compose.split('\n')
  const start = lines.findIndex((l) => l === `  ${service}:`)
  if (start < 0) return []
  let end = lines.findIndex((l, i) => i > start && /^ {0,2}\S/.test(l))
  if (end < 0) end = lines.length
  const block = lines.slice(start + 1, end)
  const pi = block.findIndex((l) => l === '    ports:')
  if (pi < 0) return []
  const out: Port[] = []
  let cur: Port | null = null
  for (const raw of block.slice(pi + 1)) {
    if (/^ {4}\S/.test(raw)) break // next service key ends the ports list
    const line = raw.replace(/#.*$/, '').trimEnd()
    if (!line.trim()) continue
    const m = line.match(/^ {6}(- )?\s*(host_ip|published|target):\s*(\S+)$/)
    if (!m) throw new Error(`unexpected port line: ${raw}`)
    if (m[1]) { cur = { published: 0, target: 0 }; out.push(cur) }
    if (!cur) throw new Error('port field before entry')
    if (m[2] === 'host_ip') cur.host_ip = m[3]
    else cur[m[2] as 'published' | 'target'] = parseInt(m[3], 10)
  }
  return out
}

describe('agent ports bind to loopback by default', () => {
  it('plain standalone compose: API port on 127.0.0.1', () => {
    const ports = portsOf(generateStandaloneCompose('a', 8652, '/d/a'), 'hermes-a')
    expect(ports).toEqual([{ host_ip: '127.0.0.1', published: 8652, target: 8642 }])
  })
  it('VPN compose: every published port on loopback', () => {
    const ports = portsOf(generateStandaloneCompose('a', 8652, '/d/a', { vpnEnabled: true }), 'wireguard')
    expect(ports.map((p) => p.host_ip)).toEqual(['127.0.0.1', '127.0.0.1', '127.0.0.1'])
    expect(ports[0]).toEqual({ host_ip: '127.0.0.1', published: 8652, target: 8642 })
  })
  it('apiBindHost overrides the API port only', () => {
    const ports = portsOf(generateStandaloneCompose('a', 8652, '/d/a', { vpnEnabled: true, apiBindHost: '192.0.2.5' }), 'wireguard')
    expect(ports.map((p) => p.host_ip)).toEqual(['192.0.2.5', '127.0.0.1', '127.0.0.1'])
  })
  it('deploy-wizard compose: API and Google OAuth ports on loopback', () => {
    const c = generateAgentCompose('a', 8652, '/d/a', { image: 'img:1' }, { googleMcpDir: '/g' })
    const ports = portsOf(c, 'hermes-a')
    expect(ports).toEqual([
      { host_ip: '127.0.0.1', published: 8652, target: 8642 },
      { host_ip: '127.0.0.1', published: 9105, target: 8095 },
    ])
  })
  it('no generated compose publishes on all interfaces', () => {
    const all = [
      generateStandaloneCompose('a', 8652, '/d/a'),
      generateStandaloneCompose('a', 8652, '/d/a', { vpnEnabled: true }),
      generateAgentCompose('a', 8652, '/d/a', { image: 'img:1' }, { googleMcpDir: '/g' }),
    ]
    for (const c of all) expect(c).not.toMatch(/^\s*- published:/m)
  })
})

describe('bindUnpinnedPorts (in-place migration of old composes)', () => {
  const OLD = `# Generated by hermes-swarm-map — agent: iris
services:
  hermes-iris:
    image: img:1
    ports:
      - published: 8712
        target: 8642
      - published: 9165
        target: 8095   # Google OAuth callback
    volumes:
      - /d:/opt/data
`
  it('pins unpinned entries to loopback and keeps YAML valid', () => {
    const out = bindUnpinnedPorts(OLD)
    expect(portsOf(out, 'hermes-iris')).toEqual([
      { host_ip: '127.0.0.1', published: 8712, target: 8642 },
      { host_ip: '127.0.0.1', published: 9165, target: 8095 },
    ])
  })
  it('is idempotent', () => {
    const once = bindUnpinnedPorts(OLD)
    expect(bindUnpinnedPorts(once)).toBe(once)
  })
  it('leaves entries that already name a host_ip alone', () => {
    const vpn = generateStandaloneCompose('a', 8652, '/d/a', { vpnEnabled: true, vncBindHost: '192.0.2.9' })
    expect(bindUnpinnedPorts(vpn)).toBe(vpn)
  })
  it('never touches a compose HSM did not generate', () => {
    const foreign = OLD.replace('# Generated by hermes-swarm-map — agent: iris', '# my own file')
    expect(bindUnpinnedPorts(foreign)).toBe(foreign)
  })
  it('refuses a host value that could inject YAML', () => {
    expect(() => bindUnpinnedPorts(OLD, '0.0.0.0\n    privileged: true')).toThrow()
    expect(() => bindUnpinnedPorts(OLD, '1.2.3.4 # x')).toThrow()
  })
  it('default host is loopback', () => {
    expect(DEFAULT_API_BIND_HOST).toBe('127.0.0.1')
  })
})

describe('parsePublishedPorts counts every host IP', () => {
  it('reads loopback, 0.0.0.0 and IPv6 bindings, skips unpublished', () => {
    const out = [
      '127.0.0.1:8652->8642/tcp',
      '0.0.0.0:8682->8642/tcp, [::]:8682->8642/tcp',
      '8080/tcp',
      '127.0.0.1:5902->5900/tcp, 127.0.0.1:6082->6080/tcp',
    ].join('\n')
    expect(parsePublishedPorts(out)).toEqual([8652, 8682, 8682, 5902, 6082])
  })
})

describe('apiBindHost setting validation', () => {
  it('accepts addresses and empty', () => {
    expect(validateSettingsPatch({ apiBindHost: '127.0.0.1' })).toEqual({ apiBindHost: '127.0.0.1' })
    expect(validateSettingsPatch({ apiBindHost: '::1' })).toEqual({ apiBindHost: '::1' })
    expect(validateSettingsPatch({ apiBindHost: '' })).toEqual({ apiBindHost: '' })
  })
  it('rejects anything that is not an address', () => {
    expect(() => validateSettingsPatch({ apiBindHost: '1.2.3.4 # x' })).toThrow()
    expect(() => validateSettingsPatch({ apiBindHost: 'a\nb' })).toThrow()
    expect(() => validateSettingsPatch({ apiBindHost: 5 })).toThrow()
  })
})
